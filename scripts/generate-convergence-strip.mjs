#!/usr/bin/env node
/**
 * generate-convergence-strip.mjs
 *
 * Regenerates the CONVERGENCE strip on the FIELD INDEX root page and the
 * companion data file. GENERATED — do not hand-edit the strip block.
 *
 * Reads:
 *   control/CURRENT.json      (active fronts, heads, updated)
 *   control/WORKER_BOOT.json  (gaps, execution)
 *   control/QUEUE.json        (live count, max_live)
 *   git                       (commits today, branch count, recent subjects)
 *
 * Writes:
 *   control/convergence-strip.json   (data)
 *   index.html                        (injects between markers)
 *
 * Usage: node scripts/generate-convergence-strip.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(ROOT, p), 'utf8'));
const raw = (p, d = '') => (existsSync(join(ROOT, p)) ? readFileSync(join(ROOT, p), 'utf8') : d);
const git = (cmd, d = '') => { try { return execSync(cmd, { cwd: ROOT, encoding: 'utf8' }).trim(); } catch { return d; } };
const esc = (s) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

const current = existsSync(join(ROOT, 'control/CURRENT.json')) ? read('control/CURRENT.json') : {};
const queue = existsSync(join(ROOT, 'control/QUEUE.json')) ? read('control/QUEUE.json') : {};
const boot = existsSync(join(ROOT, 'control/WORKER_BOOT.json')) ? read('control/WORKER_BOOT.json') : {};

const today = new Date().toISOString().slice(0, 10);
const commitsToday = git(`git log --since="${today}T00:00:00" --oneline | wc -l`, '0').trim();
const branchCount = git('git branch -r | grep -v HEAD | wc -l', '0').trim();
const recent = git('git log --oneline -3 --format=%s', '')
  .split('\n').filter(Boolean).map((s) => s.slice(0, 78));

const fronts = (current.active_fronts || []).map((f) => ({
  id: f.id, state: f.state, center: f.center
}));
const heads = (current.current_heads || []).length;
const liveCount = (queue.live || []).length;
const maxLive = queue.max_live || 3;
const gaps = (boot.open_gaps || []).map((g) => ({ id: g.id, status: g.status }));

const data = {
  schema: '0xxx0/convergence-strip/v0.1',
  generated: new Date().toISOString(),
  generator: 'scripts/generate-convergence-strip.mjs',
  commits_today: Number(commitsToday) || 0,
  branch_count: Number(branchCount) || 0,
  recent_commits: recent,
  active_fronts: fronts,
  live_fronts: `${liveCount}/${maxLive}`,
  current_heads: heads,
  open_gaps: gaps,
  current_updated: current.updated || '?'
};
writeFileSync(join(ROOT, 'control/convergence-strip.json'), JSON.stringify(data, null, 2) + '\n');
console.log('wrote control/convergence-strip.json');

// ---- render the strip HTML (static, no JS required) ----
const dot = (s) => ({
  ACTIVE_NOW: 'hot', ACTIVE: 'green', ACTIVE_MAINTENANCE: 'cool', HOLD: 'mut'
}[s] || 'mut');

const frontRows = fronts.map((f) =>
  `<a class="csFront" href="./control/CURRENT.json"><i class="csDot ${dot(f.state)}"></i><b>${esc(f.id || '?')}</b><span>${esc((f.center || '').replace(/^\//, '').slice(0, 46))}</span></a>`
).join('');

const gapRows = gaps.map((g) =>
  `<span class="csGap ${g.status === 'BLOCKED' || g.status === 'BLOCKED_EXTERNAL' ? 'bad' : 'mut'}">${esc(g.id)}</span>`
).join('');

const commitRows = recent.map((s) => `<li>${esc(s)}</li>`).join('');

// ---- plain reading projection (READFIELD reads the strip's own source) ----
const plainMd = [
  `# CONVERGENCE — plain reading`,
  ``,
  `_Generated ${data.generated} by scripts/generate-convergence-strip.mjs_`,
  ``,
  `The field has **${data.commits_today} commits today** across **${data.branch_count} branches**.`,
  `**${data.live_fronts}** fronts are live, against **${data.current_heads}** current heads.`,
  `There are **${gaps.length}** open gaps.`,
  ``,
  `## Active fronts`,
  ``,
  ...fronts.map((f) => `- **${f.id}** (${f.state}) — ${f.center}`),
  ``,
  `## Last commits`,
  ``,
  ...recent.map((s) => `- ${s}`),
  ``,
  `## Open gaps`,
  ``,
  ...gaps.map((g) => `- ${g.id} — ${g.status}`),
  ``,
  `## Law`,
  ``,
  `RECOVER BEFORE INVENTING.`,
  ``,
  `Transfer of power: /control/confluence/TRANSFER_OF_POWER_2026-09-22.md`,
  ``
].join('\n');
writeFileSync(join(ROOT, 'control/convergence-plain.md'), plainMd);
console.log('wrote control/convergence-plain.md');

const strip = `<!-- CONVERGENCE-STRIP:START (generated by scripts/generate-convergence-strip.mjs — do not hand-edit) -->
<section class="cstrip" aria-label="Convergence state">
  <div class="csHead">
    <span class="csEy">CONVERGENCE · ${esc(data.generated.slice(0, 16).replace('T', ' '))}Z</span>
    <span class="csLaw">RECOVER BEFORE INVENTING</span>
  </div>
  <div class="csGrid">
    <a class="csCell" href="./nexus/">
      <b class="csNum hot">${data.commits_today}</b><span>commits today</span>
    </a>
    <a class="csCell" href="./nexus/board.html">
      <b class="csNum cool">${data.branch_count}</b><span>active branches</span>
    </a>
    <a class="csCell" href="./control/QUEUE.json">
      <b class="csNum green">${esc(data.live_fronts)}</b><span>live fronts</span>
    </a>
    <a class="csCell" href="./control/CURRENT.json">
      <b class="csNum">${data.current_heads}</b><span>current heads</span>
    </a>
    <a class="csCell" href="./control/CURRENT.json">
      <b class="csNum gold">${fronts.length}</b><span>active fronts</span>
    </a>
    <a class="csCell" href="./control/WORKER_BOOT.json">
      <b class="csNum ${gaps.some((g) => /BLOCK/.test(g.status)) ? 'bad' : 'green'}">${gaps.length}</b><span>open gaps</span>
    </a>
  </div>
  <div class="csBody">
    <div class="csCol">
      <span class="csColEy">FRONTS</span>
      ${frontRows || '<span class="csGap mut">none active</span>'}
    </div>
    <div class="csCol">
      <span class="csColEy">LAST COMMITS</span>
      <ul class="csCommits">${commitRows || '<li>—</li>'}</ul>
    </div>
    <div class="csCol">
      <span class="csColEy">OPEN GAPS</span>
      <div class="csGaps">${gapRows || '<span class="csGap green">none</span>'}</div>
    </div>
  </div>
  <div class="csFootRow">
    <a class="csFoot" href="./docs/?src=/control/convergence-strip.json&return=/">◉ READ PLAIN — READFIELD/RSVP reads this state →</a>
    <a class="csFoot" href="./control/confluence/TRANSFER_OF_POWER_2026-09-22.md">◈ TRANSFER OF POWER →</a>
  </div>
</section>
<!-- CONVERGENCE-STRIP:END -->`;

const indexPath = join(ROOT, 'index.html');
let html = readFileSync(indexPath, 'utf8');
const START = '<!-- CONVERGENCE-STRIP:START';
const END = '<!-- CONVERGENCE-STRIP:END -->';
const si = html.indexOf(START);
const ei = html.indexOf(END);

if (si !== -1 && ei !== -1) {
  html = html.slice(0, si) + strip + html.slice(ei + END.length);
} else {
  // first insert: right after the .reentry bar
  const anchor = '</div>\n\n<section class="axial"';
  const idx = html.indexOf(anchor);
  if (idx === -1) { console.error('insert anchor not found'); process.exit(1); }
  html = html.slice(0, idx + '</div>'.length) + '\n' + strip + '\n' + html.slice(idx + '</div>'.length);
}
writeFileSync(indexPath, html);
console.log('injected strip into index.html');

// ---- CSS (idempotent block at end of <style>) ----
const CSS_START = '/* CONVERGENCE-STRIP:START */';
const CSS_END = '/* CONVERGENCE-STRIP:END */';
let css = `/* CONVERGENCE-STRIP:START */
.cstrip{margin-top:8px;border:1px solid var(--line);background:linear-gradient(180deg,#0b0f11,#080b0d)}
.csHead{display:flex;justify-content:space-between;gap:8px;align-items:center;padding:5px 8px;border-bottom:1px solid var(--line);background:#0a0e10}
.csEy{font-size:6.5px;letter-spacing:.16em;color:var(--hot)}
.csLaw{font-size:6px;letter-spacing:.1em;color:var(--mut)}
.csGrid{display:grid;grid-template-columns:repeat(6,1fr);gap:1px;background:var(--line)}
.csCell{background:#090d0f;padding:7px 8px;display:block;min-width:0}
.csCell:hover{background:#0d1316}
.csCell .csNum{font:800 19px/1 system-ui,sans-serif;letter-spacing:-.02em;display:block}
.csCell span{display:block;color:var(--mut);font-size:6px;letter-spacing:.08em;margin-top:3px;text-transform:uppercase;white-space:nowrap;overflow:hidden;text-overflow:ellipsis}
.csBody{display:grid;grid-template-columns:1.1fr 1.4fr 1fr;gap:1px;background:var(--line)}
.csCol{background:#090d0f;padding:7px 9px;min-width:0}
.csColEy{display:block;font-size:6px;letter-spacing:.13em;color:var(--mut);margin-bottom:5px}
.csFront{display:grid;grid-template-columns:8px auto minmax(0,1fr);gap:5px;align-items:center;padding:3px 0;border-bottom:1px dotted #1a2125;font-size:8px;color:var(--ink)}
.csFront:last-child{border-bottom:0}
.csFront b{font-weight:700;font-size:8px}
.csFront span{color:var(--mut);font-size:6.5px;white-space:nowrap;overflow:hidden;text-overflow:ellipsis}
.csDot{width:6px;height:6px;border-radius:50%;display:inline-block}
.csDot.hot{background:var(--hot)}.csDot.green{background:var(--green)}.csDot.cool{background:var(--cool)}.csDot.mut{background:var(--mut)}
.csCommits{list-style:none;margin:0;padding:0;font-size:7px;color:#aeb8bd;line-height:1.5}
.csCommits li{white-space:nowrap;overflow:hidden;text-overflow:ellipsis;padding:2px 0;border-bottom:1px dotted #1a2125}
.csCommits li:last-child{border-bottom:0}
.csGaps{display:flex;flex-wrap:wrap;gap:3px}
.csGap{font-size:6.5px;padding:2px 5px;border:1px solid var(--line);letter-spacing:.04em}
.csGap.bad{border-color:#5a3a3f;color:var(--bad)}
.csGap.mut{color:var(--mut)}
.csGap.green{border-color:#315837;color:var(--green)}
.csFootRow{display:grid;grid-template-columns:1.6fr 1fr;gap:1px;background:var(--line);border-top:1px solid var(--line)}
.csFoot{display:block;padding:6px 9px;font-size:7px;letter-spacing:.08em;color:var(--gold);background:#0a0e10;height:100%}
.csFoot:hover{color:#fff;background:#12181b}
@media(max-width:760px){.csFootRow{grid-template-columns:1fr}}
@media(max-width:760px){.csGrid{grid-template-columns:repeat(3,1fr)}.csBody{grid-template-columns:1fr}.csCell .csNum{font-size:16px}}
/* CONVERGENCE-STRIP:END */`;

let head = readFileSync(indexPath, 'utf8');
const ci = head.indexOf(CSS_START);
let styleClose = head.indexOf('</style>');
if (ci !== -1) {
  const ce = head.indexOf(CSS_END);
  head = head.slice(0, ci) + css + head.slice(ce + CSS_END.length);
} else {
  head = head.slice(0, styleClose) + css + '\n' + head.slice(styleClose);
}
writeFileSync(indexPath, head);
console.log('injected strip CSS into index.html');