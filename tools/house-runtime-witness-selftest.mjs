import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
let pass=0,fail=0;
const ok=(name,cond,detail='')=>{if(cond){pass++;console.log('  PASS  '+name)}else{fail++;console.log('  FAIL  '+name+(detail?' — '+detail:''))}};
const src=fs.readFileSync(path.join(ROOT,'house/runtime-witness.js'),'utf8');
const ctx={console,Date,module:{exports:{}},exports:{}};ctx.globalThis=ctx;
vm.createContext(ctx);vm.runInContext(src,ctx,{filename:'house/runtime-witness.js'});
const C=ctx.module.exports;
console.log('\n[HOUSE runtime witness freshness]');
ok('exports pure core',!!C&&typeof C.classifyAge==='function'&&typeof C.describe==='function');
const now=Date.parse('2026-10-02T13:00:00Z');
ok('10 minute snapshot is CURRENT',C.classifyAge('2026-10-02T12:50:00Z',now).freshness==='CURRENT');
ok('90 minute snapshot is RECENT',C.classifyAge('2026-10-02T11:30:00Z',now).freshness==='RECENT');
ok('3 hour snapshot is AGED',C.classifyAge('2026-10-02T10:00:00Z',now).freshness==='AGED');
const stale=C.classifyAge('2026-09-20T12:20:41Z',now);
ok('Sep-20 witness is STALE on Oct-2',stale.freshness==='STALE',JSON.stringify(stale));
ok('future timestamp fails to CLOCK_SKEW',C.classifyAge('2026-10-02T14:00:00Z',now).freshness==='CLOCK_SKEW');
const d=C.describe({generated_at:'2026-09-20T12:20:41Z',runtime_health_class:'HEALTHY',source_age_class:'FRESH',counts:{objects:32}},now);
ok('historical source freshness is labeled at-generation only',d.freshness==='STALE'&&d.source_age_at_generation==='FRESH');
ok('historical runtime health is labeled at-generation only',d.runtime_health_at_generation==='HEALTHY');
const html=fs.readFileSync(path.join(ROOT,'house/index.html'),'utf8');
ok('/house/ loads runtime witness module',/runtime-witness\.js/.test(html));
ok('legacy embedded FRESH display removed',!/houseRuntimeMeta\.textContent='generated '.+source_age_class/.test(html));
console.log(`\n${pass} passed, ${fail} failed`);
if(fail)process.exit(1);
