#!/usr/bin/env node
// check-commit-thinking.mjs — KERNEL law 8: a change carries its reasoning.
//
// WHY this exists: 656 of 702 substantive commits in this repo carried a subject and no
// body. The seller's own words: "explain your thoughts in all your commits … are you only
// executing refined prompts". A subject records that something ran; the body records the
// judgment. Without it the next session re-litigates a decided question, or worse, reads a
// diff as intent and reverses a deliberate trade.
//
// WHAT IT ENFORCES (per substantive commit):
//   - a body of >= MIN_BODY characters
//   - at least MIN_SIGNALS of the reasoning markers: why / because / reject / instead /
//     falsif / trade-off / decided
//
// WHAT IT EXEMPTS (and says so, out loud): machine-generated refresh commits, which carry no
// judgment to record. Exemption is by SUBJECT PREFIX, listed below — adding a prefix is a
// decision, so it belongs in a reviewed commit, never a silent edit.
//
// Usage:
//   node tools/check-commit-thinking.mjs                 # last N commits (default 50)
//   node tools/check-commit-thinking.mjs --n 200         # wider window
//   node tools/check-commit-thinking.mjs --range a..b    # explicit range
//   node tools/check-commit-thinking.mjs --json           # machine-readable receipt
//
// Exit 1 when any substantive commit fails. Exit 0 when the window is clean.

import {execFileSync} from 'node:child_process';

const MIN_BODY = 120;
const MIN_SIGNALS = 2;

// Prefixes of commits whose body is generated by a cron/pipeline. These record a refresh,
// not a decision. Keep the list small and justified.
const AUTO = [
  'comms:', 'nexus:', 'convergence:', 'desk:', 'calls:', 'fi-mutation-contract:',
  'sitemap:', 'release:', 'control:', 'heartbeat:', 'watch:', 'refresh:'
];

const SIGNALS = [
  /\bwhy\b/i, /\bbecause\b/i, /\breject(ed|s|ing)?\b/i, /\binstead\b/i,
  /\bfalsif(y|ies|ied|ier)\b/i, /\btrade[- ]?off\b/i, /\bdecided?\b/i,
  /\bchose|chosen\b/i, /\bnot\b.*\bbecause\b/i
];

function arg(name, fallback) {
  const i = process.argv.indexOf(name);
  return i > -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}
const asJson = process.argv.includes('--json');
const range = arg('--range', null);
const n = Number(arg('--n', 50));

const fmt = '%H%x1f%s%x1f%b%x1e';
const gitArgs = ['log', '--format=' + fmt];
if (range) gitArgs.push(range); else gitArgs.push('-n', String(n));

let raw = '';
try {
  raw = execFileSync('git', gitArgs, {encoding: 'utf8', maxBuffer: 64 * 1024 * 1024});
} catch (error) {
  console.error('check-commit-thinking: git log failed — ' + (error.message || error));
  process.exit(2);
}

const commits = raw.split('\x1e').map((chunk) => chunk.trim()).filter(Boolean).map((chunk) => {
  const [hash, subject, ...body] = chunk.split('\x1f');
  return {hash: hash.trim(), subject: subject.trim(), body: body.join('\x1f').trim()};
});

const isAuto = (subject) => AUTO.some((prefix) => subject.startsWith(prefix));

const results = commits.map((commit) => {
  const auto = isAuto(commit.subject);
  const signals = SIGNALS.reduce((count, re) => count + (re.test(commit.body) ? 1 : 0), 0);
  const ok = auto || (commit.body.length >= MIN_BODY && signals >= MIN_SIGNALS);
  return {...commit, auto, signals, ok, reason: auto ? 'auto-refresh' : ok ? 'reasoned'
    : commit.body.length === 0 ? 'no body'
    : commit.body.length < MIN_BODY ? 'body too short (' + commit.body.length + ')'
    : 'body states no reasoning marker'};
});

const substantive = results.filter((r) => !r.auto);
const failed = substantive.filter((r) => !r.ok);

if (asJson) {
  console.log(JSON.stringify({
    window: range || ('last ' + n), commits: results.length, substantive: substantive.length,
    auto: results.length - substantive.length, failing: failed.length,
    pass_rate: substantive.length ? +(100 * (substantive.length - failed.length) / substantive.length).toFixed(1) : 100,
    failures: failed.map((f) => ({hash: f.hash.slice(0, 9), subject: f.subject.slice(0, 72), reason: f.reason}))
  }, null, 2));
} else {
  if (failed.length) {
    console.log('THINKING GATE — ' + failed.length + ' of ' + substantive.length + ' substantive commits state no reasoning\n');
    for (const f of failed.slice(0, 15)) console.log('  ' + f.hash.slice(0, 9) + '  ' + f.reason.padEnd(34) + f.subject.slice(0, 62));
    if (failed.length > 15) console.log('  … ' + (failed.length - 15) + ' more');
    console.log('\nA body needs: WHY this is right · WHAT was rejected and why · WHAT WOULD FALSIFY IT');
  } else {
    console.log('THINKING GATE OK — ' + substantive.length + ' substantive commits, every one carries reasoning');
  }
  console.log('\nwindow ' + (range || ('last ' + n)) + ' · ' + results.length + ' commits · '
    + substantive.length + ' substantive · ' + (results.length - substantive.length) + ' auto-refresh exempt');
}

process.exit(failed.length ? 1 : 0);
