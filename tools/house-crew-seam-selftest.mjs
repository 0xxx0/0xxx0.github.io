import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
let pass=0,fail=0;
const ok=(name,cond,detail='')=>{if(cond){pass++;console.log('  PASS  '+name)}else{fail++;console.log('  FAIL  '+name+(detail?' — '+detail:''))}};
function load(file){
 const src=fs.readFileSync(path.join(ROOT,file),'utf8');
 const ctx={console,Date,Math,module:{exports:{}},exports:{}};ctx.globalThis=ctx;
 vm.createContext(ctx);vm.runInContext(src,ctx,{filename:file});return{api:ctx.module.exports,src};
}
const crew=load('house/crew-seam.js'),C=crew.api;
const carrier=load('lib/interphase-carrier.js').api;
console.log('\n[HOUSE crew seam]');
ok('exports bounded schemas',C.FRAME_SCHEMA==='house-crew-frame/v0.1'&&C.OFFER_SCHEMA==='house-crew-offer/v0.1'&&C.RESPONSE_SCHEMA==='house-crew-response/v0.1');
let f=C.makeFrame({context:{address:'living_dining',label:'Living / Dining',projection:'PLAN'},design:{focus_step:'before',missing:['before','intent']},runtime:{freshness:'STALE'}});
ok('before requires world return',f.human_gate.class==='WORLD_RETURN');
f=C.makeFrame({context:{address:'living_dining'},design:{focus_step:'intent',missing:['intent']}});
ok('intent remains human choice',f.human_gate.class==='CHOOSE');
f=C.makeFrame({context:{address:'living_dining'},design:{trial_id:'t1',focus_step:'change',intent:'clear the work route',constraints:'keep cat path open',missing:['change']}});
ok('crew may proceed at proposal phase',f.human_gate.class==='NONE'&&f.next.some(x=>x.id==='PROPOSE_CHANGE'));
ok('intent + constraint survive without duplicate form',f.intent.text==='clear the work route'&&f.constraints[0]==='keep cat path open');
f=C.makeFrame({context:{address:'living_dining'},design:{focus_step:'after',intent:'clear route',change:'move trolley',missing:['after']}});
ok('after-state returns to human/world',f.human_gate.class==='WORLD_RETURN');
f=C.makeFrame({context:{address:'living_dining'},design:{focus_step:'return',state:'RETURN_READY'}});
ok('ready receipt asks only a ping',f.human_gate.class==='PING');
ok('next remains at most three',f.next.length<=3);
const badAddr=C.validateOffer({schema:C.OFFER_SCHEMA,authority:'OFFER_ONLY',object:{address:'kitchen'},proposals:[{id:'p1',label:'check',kind:'CHECK'}]},f);
ok('wrong-locus offer fails closed',!badAddr.ok&&badAddr.errors.includes('address'));
const badEffect=C.validateOffer({schema:C.OFFER_SCHEMA,authority:'OFFER_ONLY',object:{address:'living_dining'},proposals:[{id:'p1',label:'act',kind:'PROPOSE',effect:true}]},f);
ok('effect-bearing offer rejected',!badEffect.ok);
const good=C.validateOffer({schema:C.OFFER_SCHEMA,authority:'OFFER_ONLY',from:{id:'worker-1'},object:{address:'living_dining'},summary:'bounded options',proposals:[{id:'p1',label:'compare two trolley positions',kind:'PROPOSE'},{id:'p2',label:'check 700mm path',kind:'CHECK'}]},f);
ok('bounded exact-locus offer accepted',good.ok&&good.offer.proposals.length===2);
const response=C.makeResponse('WRONG_FRAME',good.offer,f);
ok('human correction is coordination only',response.action==='WRONG_FRAME'&&response.authority==='COORDINATION_ONLY'&&/reframe/i.test(response.meaning));
const ipc=C.compileCarrier(f,carrier);
ok('compiles through existing INTERPHASE carrier',ipc?.schema==='interphase-carrier/v0.1'&&ipc.authority==='NONE / HANDOFF ONLY'&&ipc.projection.name==='CREW');
ok('carrier cannot execute effects',ipc.next.every(x=>x.dispatch==='HOST_NATIVE_ONLY'));
const a=C.makeFrame({context:{address:'living_dining'},design:{focus_step:'change',intent:'a'}}),b=C.makeFrame({context:{address:'living_dining'},design:{focus_step:'change',intent:'b'}});
ok('delta reports changed coordination field',C.changed(a,b).includes('intent'));
ok('no whole-state fingerprint/correlation primitive',!/fingerprint|hashString|whole.state/i.test(crew.src));
const rh=fs.readFileSync(path.join(ROOT,'house/reality-harness.js'),'utf8');
ok('reality harness exposes CREW / AGENT',/CREW \/ AGENT/.test(rh));
ok('reality harness loads crew seam',/crew-seam\.js/.test(rh)&&/interphase-carrier\.js/.test(rh));
ok('one-bit crew responses visible',/KEEP/.test(rh)&&/PARK/.test(rh)&&/WRONG FRAME/.test(rh));
console.log(`\n${pass} passed, ${fail} failed`);
if(fail)process.exit(1);
