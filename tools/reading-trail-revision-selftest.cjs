const assert=require('node:assert/strict');
const Trail=require('../lib/read-trail.js'),Review=require('../lib/readfield-review.js');
const mem=new Map(),store={getItem:key=>mem.get(key)||null,setItem:(key,value)=>mem.set(key,value),removeItem:key=>mem.delete(key)};
const key='address:/control/CURRENT.json',A='sha256:'+'a'.repeat(64),B='sha256:'+'b'.repeat(64);
let x=Trail.record(key,{progress:.55,charIndex:55,revision:A,address:'WORD/55',via:'READFIELD'},store);
assert.equal(x.furthest,.55);assert.equal(x.furthestRevision,A);assert.equal(x.last.revision,A);
x=Trail.record(key,{progress:.18,charIndex:18,revision:A,via:'READFIELD_WRIST'},store);
assert.equal(x.furthest,.55,'revisiting an earlier point retains max only within same exact revision');
Trail.setMarks(key,[{id:'review:'+A+':0:5',revision:A,charIndex:0,endIndex:5,quote:'alpha',kind:'QUESTION',note:'Why alpha?',progress:0}],store);
x=Trail.record(key,{progress:.12,charIndex:12,revision:B,via:'READFIELD_WRIST'},store);
assert.equal(x.furthest,.12,'changed bytes do not inherit previous visited extent');
assert.equal(x.furthestRevision,B);assert.equal(x.last.revision,B);
assert.equal(x.marks.length,1,'old authored work is retained after revision change');
assert.equal(Review.bound(x.marks[0],{raw:'bravo, different source',revision:B}),false,'stale quote is not silently reattached');
x=Trail.record(key,{progress:.42,charIndex:42,revision:B},store);
assert.equal(x.furthest,.42);
x=Trail.record(key,{progress:.91,charIndex:91},store);
assert.equal(x.furthestRevision,'','legacy/unversioned clients demote proof instead of promoting into current revision');
assert.equal(x.last.revision,'');
assert.equal(x.marks[0].revision,A,'revision-bound annotations survive legacy writes without reassignment');
x=Trail.record(key,{progress:.10,charIndex:10,revision:B},store);
assert.equal(x.furthest,.10,'returning to exact revision resets extent after unbound traversal');
assert.equal(x.furthestRevision,B);
const legacy={sourceKey:key,furthest:.9,last:{charIndex:90,progress:.9},marks:[]};
x=Trail.normalize(legacy,key);
assert.equal(x.furthestRevision,'');assert.equal(x.last.revision,'','legacy visits remain unbound, not fraudulently exact');
console.log('SOURCE TRAIL REVISION PASS · shared path · exact visited reset · stale notes parked · legacy demotion');
