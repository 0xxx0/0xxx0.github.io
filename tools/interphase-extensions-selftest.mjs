import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import U from '../lib/interphase.mjs';
import vector, {dot} from '../interphase/extensions/vector.mjs';
const require=createRequire(import.meta.url),E=U.extensions,T=U.contracts;
assert.equal(U.core,require('../lib/interphase-core.js'));
assert.equal(U.constraints,require('../lib/constraint-surface.js'));
const title=E.fromJSON(JSON.parse(readFileSync(new URL('../interphase/extensions/title.json',import.meta.url),'utf8')));
const catalog=E.compose(E.native,title,vector),s=U.lenses.createGenesisObject();
assert.equal((await E.loadModule('../interphase/extensions/vector.mjs')).id,'vector');
assert.equal(E.check(catalog,'object',s).ok,true);
assert.equal(E.inspect(catalog,s).titleBounds.ok,true);
assert.equal(E.inspect(catalog,{...s,title:''}).titleBounds.ok,false);
assert.equal(E.propose(catalog,'dot',[2,3],{b:[4,5]}),23);
const frozen=E.propose(catalog,'trim',{...s,title:' spaced '});assert.equal(frozen.title,'spaced');assert.ok(Object.isFrozen(frozen));assert.equal(s.title,'INTERPHASE');
const p=(id,extra={})=>E.define({protocol:E.protocol,id,version:'1.0.0',...extra});
const base=E.compose(p('a'));assert.throws(()=>E.compose(p('a'),p('a')),/duplicate plugin/);assert.equal(base.plugins.length,1);
assert.throws(()=>E.compose(p('a',{requires:{b:'1.0.0'}})),/missing exact dependency/);
assert.throws(()=>E.compose(p('a',{requires:{b:'1.0.0'}}),p('b',{requires:{a:'1.0.0'}})),/dependency cycle/);
assert.deepEqual(E.compose(p('a',{requires:{b:'1.0.0'}}),p('b')).plugins.map(p=>p.id),['b','a']);
assert.throws(()=>E.compose(p('a',{types:{x:()=>true}}),p('b',{types:{x:()=>false}})),/duplicate types/);
assert.throws(()=>E.fromJSON({protocol:E.protocol,id:'bad',version:'1.0.0',operators:{eval:'alert(1)'}}),/JSON only/);
assert.throws(()=>E.fromJSON({protocol:E.protocol,id:'bad',version:'1.0.0',types:{x:{kind:'number',min:Infinity}}}),/finite bound/);
assert.throws(()=>E.define({protocol:'old',id:'a',version:'1.0.0'}));
assert.throws(()=>dot([1],[1,2]),/equal finite vectors/);
assert.throws(()=>dot([Infinity],[2]));assert.throws(()=>dot([Number.MAX_VALUE],[2]),/overflow/);
const mutator=E.compose(p('mutator',{operators:{mutate:x=>{x.title='bad';return x}}}));assert.throws(()=>E.propose(mutator,'mutate',s));assert.equal(s.title,'INTERPHASE');
const law=T.property('dot commutes',r=>[T.genArray(T.genInt(-100,100),4,4)(r),T.genArray(T.genInt(-100,100),4,4)(r)],([a,b])=>dot(a,b)===dot(b,a),{seed:42,runs:400});
assert.equal(law.ok,true,JSON.stringify(law));
console.log('EXTENSIONS PASS: transport-independent API, identity, transactional conflicts, exact dependencies/cycles, JSON no-eval, immutability, bounds, finite math, 400 seeded dot laws');
