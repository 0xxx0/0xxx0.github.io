import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
let pass=0,fail=0;
const ok=(name,cond,detail='')=>{if(cond){pass++;console.log('  PASS  '+name)}else{fail++;console.log('  FAIL  '+name+(detail?' — '+detail:''))}};
const src=fs.readFileSync(path.join(ROOT,'house/human-harness.js'),'utf8');
const ctx={console,Date,TextEncoder,module:{exports:{}},exports:{}};ctx.globalThis=ctx;
vm.createContext(ctx);vm.runInContext(src,ctx,{filename:'house/human-harness.js'});
const C=ctx.module.exports;
const model=JSON.parse(fs.readFileSync(path.join(ROOT,'house/human-harness.json'),'utf8'));

console.log('\n[HOUSE ENV-0 human harness]');
ok('model schema',model.schema==='house-human-harness/v0.1');
ok('six named reality layers',['BODY','HARNESS','OBJECT','ROOM','HOUSE','NETWORK'].every(id=>model.layers.some(x=>x.id===id)));
ok('execution phases are distinct from layers',JSON.stringify(C.PHASES)===JSON.stringify(['UNBOUND','ORIENTED','EQUIPPED','ENGAGED','ACTED','WITNESSED','RETURNED']));
ok('four human gates',['NONE','PING','CHOOSE','WORLD_RETURN'].every(x=>C.GATES.includes(x)));
ok('public state without locus is UNBOUND',C.makeState({}).phase==='UNBOUND');
let s=C.makeState({context:{address:'living_dining',label:'Living / Dining'},design:{focus_step:'change',intent:'reduce friction'}});
ok('design change maps to EQUIPPED / HARNESS',s.phase==='EQUIPPED'&&s.active_layer==='HARNESS',JSON.stringify(s));
let g=C.makeState({context:{address:'living_dining'},design:{focus_step:'after'},crew:{human_gate:{class:'WORLD_RETURN',reason:'observe'}}});
ok('crew gate projects without effect authority',g.human_gate.class==='WORLD_RETURN'&&g.effect_authority==='NONE');
let base=C.makeState({context:{address:'living_dining'},design:{focus_step:'verify'}});
base.phase='ENGAGED';base.active_layer='OBJECT';
let act=C.transition(base,{type:'ACT'});
ok('ACT fails without native effect authority',!act.ok&&act.error==='NATIVE_EFFECT_AUTHORITY_REQUIRED');
act=C.transition(base,{type:'ACT',effect_authority:'HUMAN_PHYSICAL',human_gate_cleared:true});
ok('ACT succeeds only with separate authority + human gate',act.ok&&act.state.phase==='ACTED'&&act.state.effect_authority==='HUMAN_PHYSICAL');
let wit=C.transition(act.state,{type:'WITNESS',fresh:false,evidence_ref:'/returns/x.json'});
ok('WITNESS fails without fresh evidence',!wit.ok&&wit.error==='FRESH_WORLD_WITNESS_REQUIRED');
wit=C.transition(act.state,{type:'WITNESS',fresh:true,evidence_ref:'/returns/x.json'});
ok('fresh witness advances to WITNESSED',wit.ok&&wit.state.phase==='WITNESSED'&&wit.state.witness.refs[0]==='/returns/x.json');
let ret=C.transition(wit.state,{type:'RETURN'});
ok('RETURN fails without human decision',!ret.ok&&ret.error==='DECISION_REQUIRED');
ret=C.transition(wit.state,{type:'RETURN',decision:'REVISE',residue:'measure passage'});
ok('RETURN preserves decision and residue',ret.ok&&ret.state.phase==='RETURNED'&&ret.state.return.decision==='REVISE'&&ret.state.return.residue==='measure passage');
let reframe=C.transition(ret.state,{type:'REFRAME'});
ok('REFRAME requires explicit delta',!reframe.ok&&reframe.error==='FRAME_DELTA_REQUIRED');
reframe=C.transition(ret.state,{type:'REFRAME',delta:{intent:'test alternate tool home'}});
ok('REFRAME returns to ORIENTED with delta',reframe.ok&&reframe.state.phase==='ORIENTED'&&reframe.state.task.intent==='test alternate tool home');
const hi=C.makeCrewHandoffInput(s,{next:[{id:'CHECK_CONSTRAINTS',gate:'NONE'},{id:'OBSERVE_AFTER',gate:'WORLD_RETURN'}]});
ok('handoff input exposes only ungated crew moves',hi.allowed_moves.length===1&&hi.allowed_moves[0]==='CHECK_CONSTRAINTS');
ok('source contains no network client',!/(fetch\s*\(|XMLHttpRequest|WebSocket\s*\()/m.test(src));
ok('model keeps permanent work proof boundary',/structural/.test(model.safety_and_permanence.permanent_work)&&/WORLD_RETURN/.test(model.safety_and_permanence.permanent_work));
console.log(`\n${pass} passed, ${fail} failed`);
if(fail)process.exit(1);
